frase = ' Curso em Vídeo Python   '
# número total dos índices
print(len(frase))
# mostra as quantidades do item especificado
print(frase.count('n',1,20))
# a partir de que índice se encontra o item especificado
print(frase.find('deo'))
# mostra se a palavra está na frase
print('android' in frase)
# substitui a palavra escolhida por outra
print(frase.replace('Python', 'Android'))
# deixa todas as letras maiúsculas
print(frase.upper())
# deixa todas minúsculas
print(frase.lower())
# deixa apenas a primeira letra sendo maiúscula
print(frase.capitalize())
# deixa apenas as primeiras letras, após um espaço, em maiúsculas
print(frase.title())
# remove todos os espaços inúteis
print(frase.strip())
# remove os últimos espaços da direita
print(frase.rstrip())
# remove os primeiros espaços da esquerda
print(frase.lstrip())











